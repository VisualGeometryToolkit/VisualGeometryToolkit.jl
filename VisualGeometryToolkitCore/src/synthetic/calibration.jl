# =============================================================================
# The Monte-Carlo calibration harness — statistical calibration of the
# uncertainty-propagation chain (chart-domain hypothesis covariances, refit
# covariances, and — by construction — any other covariance provider, plugged
# into the trials' `estimate` / `covariance` hooks).
#
# THE OBJECT UNDER TEST. The hypothesis covariance attached to a model θ₀ is
# the local sensitivity of the constrained solution in the minimal chart
# anchored at θ₀:
#
#     Σ̃_v = J · Σ̃_x · Jᵀ,    J = −(∂_v g)⁻¹ · ∂_x g
#
# with g the stacked minimal-sample constraints. The definition involves the
# chart and the constraint system only — no estimation algorithm enters — and
# it is exact for the smooth local solution through θ₀. This is a property of
# the PROBLEM (constraint variety + chart), not of any solver.
#
# THE PROTOCOL (the established covariance-MC lineage, cf.
# the retired bench/experiment_covariance_mc.jl driver and Criminisi §4.3.3). Per trial:
#   1. sample base minimal correspondences with representative geometry —
#      their exact minimal interpolant IS θ_gt (the correspondences are
#      generated by the ground-truth geometry, hence on the constraint
#      variety by construction);
#   2. anchor the minimal chart at θ_gt;
#   3. perturb the base correspondences with a KNOWN per-point covariance
#      (unit-scale shape × σ²);
#   4. obtain the perturbed-sample solution SINGLE-VALUEDLY:
#        • H — the unique minimal solution of the perturbed sample (the
#          4-point problem is single-valued; nothing else is needed);
#        • E / F — the solution TRACKED from the ground-truth anchor by
#          damped chart-Newton continuation (`track_manifold_solution`; the
#          minimal problems are multi-rooted, and local tracking keeps the
#          trial single-valued without any root enumeration); trials where
#          the continuation fails to converge are counted and REPORTED as
#          the divergence rate — that rate, together with the magnitude of
#          Σ̃_v itself, is the honest conditioning statement for a hypothesis
#          (never reinterpreted);
#   5. compare against the analytics, in TWO domains:
#        • OUTPUT DOMAIN (the headline; Criminisi's MC validation of the
#          first-order analysis, Table 4.1 — see the driver's method text):
#          noise in BOTH the computation points and the query point; the MC
#          transferred point / epipolar line family versus the first-order
#          ellipse / H–Z band with the model and query covariance terms
#          composed (`h_transfer_trial`, `epipolar_band_trial` →
#          `run_containment`);
#        • CHART DOMAIN (secondary; validates the transport machinery):
#          NEES  e = vᵀ Σ_pred⁻¹ v ~ χ²(dof), E[e] = dof (mean +
#          median-ratio), plus empirical coverage of the χ²(dof) 50/90/95%
#          quantiles, with Σ_pred = J·Σ̃_x·Jᵀ at θ_gt.
# Failures are REPORTED, not hidden — the noise level where the linearization
# radius is genuinely exceeded is a deliverable (breakdown σ + divergence
# rate), and so are structural findings (chart-frame near-gauge degeneracy;
# predicted-covariance anisotropy beyond Float64 reach → `cond_cap`).
#
# HOW TO PLUG A PROVIDER IN (the reusable entry point). Write a trial closure
#     trial(rng) -> nothing | (v̂::AbstractVector, Σ_pred::AbstractMatrix)
# that (1) samples ground-truth geometry, (2) perturbs the measurements with
# KNOWN covariances, (3) obtains the chart-coordinate displacement of the
# estimate/tracked solution relative to the anchor, and (4) returns the
# PHYSICAL predicted covariance (unit-scale shape × σ²). Then call
# `run_calibration(trial, rng, ntrials, dof)`. The tracking trial builders
# below are examples, and take a refit and its covariance through their
# `estimate` / `covariance` hooks (see the trial-builder section).
#
# Public, not exported, in `Synthetic` (hoisted 2026-09-22 from
# test/validation/CalibrationHarness.jl, where VisualGeometryToolkitEstimation and the ACCV
# research code included it by path). Its chart machinery is the package's own:
# `manifold_constraints` / `constraint_jacobians` stack the constraints
# and their Jacobians at any chart coordinates, the functions
# `implicit_covariance` reads at the anchor.
#
# CONVENTIONS. Unit-scale covariance shapes throughout (Σ from unit
# measurement noise; σ² applied here, by the consumer — matching the
# lemma-conformant sweep convention).
# =============================================================================

# -----------------------------------------------------------------------------
# Core statistics
# -----------------------------------------------------------------------------

const COVERAGE_LEVELS = (0.5, 0.9, 0.95)

"""
Result of one MC calibration cell.

- `nees_mean`, `nees_se`: sample mean of the NEES and its standard error
  (χ² theory: sd(mean) = √(2·dof/N) under calibration).
- `coverage`: empirical fraction of trials with NEES ≤ χ²(dof) quantile at
  the levels $(COVERAGE_LEVELS).
- `emp_cov`, `mean_pred`: empirical covariance of the tracked chart errors vs
  the mean predicted covariance (for eigen-ratio diagnostics).
- `nfail`: trials discarded. For the tracking cells this is the DIVERGENCE
  count (chart-Newton continuation failed to converge — genuinely
  ill-conditioned at that noise level) plus the rare degenerate-anchor
  trials (singular ∂_v g at θ_gt); for refit cells it is fit failures.
"""
struct CalibrationResult
    dof::Float64                 # mean EFFECTIVE dof (== declared dof unless cond_cap)
    ntrials::Int
    nfail::Int
    nees_mean::Float64
    nees_se::Float64
    nees_median_ratio::Float64   # median(NEES)/median(χ²(dof)) — BULK calibration
    coverage::NTuple{3, Float64}
    emp_cov::Matrix{Float64}
    mean_pred::Matrix{Float64}
end

"""
    run_calibration(trial, rng, ntrials, dof; cond_cap=Inf) -> CalibrationResult

Run `ntrials` MC trials of `trial(rng) -> nothing | (v̂, Σ_pred)` and gather
NEES / coverage statistics against χ²(dof). See the module header for the
trial-closure contract.

`cond_cap`: with a finite value, the NEES is evaluated on the eigen-subspace
of Σ_pred with λ ≥ λ_max/cond_cap and compared against χ²(effective dof) —
per trial. This is a numerical safeguard for problems whose predicted chart
covariances are anisotropic beyond Float64 reach (predicted standard
deviations in the stiffest directions below what the arithmetic of the
tracked solve can realize — there the full-dof NEES measures ROUNDOFF, not
statistics). The capped statistic states calibration on the numerically
representable uncertainty subspace; the discarded-direction count is visible
as `dof` < declared dof.
"""
function run_calibration(
        trial, rng::AbstractRNG, ntrials::Int, dof::Int;
        cond_cap::Float64 = Inf
    )
    nees = Float64[]
    dofs = Int[]
    errs = Vector{Vector{Float64}}()
    sum_pred = zeros(dof, dof)
    nfail = 0
    for _ in 1:ntrials
        out = trial(rng)
        if out === nothing
            nfail += 1
            continue
        end
        v, Σ = out
        length(v) == dof || error("trial returned a $(length(v))-vector; expected dof = $dof")
        local e, d
        if isfinite(cond_cap)
            E = eigen(Symmetric(Matrix(Σ)))
            keep = findall(>=(E.values[end] / cond_cap), E.values)
            isempty(keep) && (nfail += 1; continue)
            z = E.vectors[:, keep]' * Vector(v)
            e = sum(z .^ 2 ./ E.values[keep])
            d = length(keep)
        else
            F = cholesky(Symmetric(Matrix(Σ)); check = false)
            if !issuccess(F)
                nfail += 1
                continue
            end
            e = dot(v, F \ Vector(v))
            d = dof
        end
        push!(nees, e)
        push!(dofs, d)
        push!(errs, Vector(v))
        sum_pred .+= Matrix(Σ)
    end
    n = length(nees)
    n == 0 && error("run_calibration: every trial failed")
    cov_emp = n > 1 ? cov(reduce(hcat, errs); dims = 2) : zeros(dof, dof)
    # per-trial χ² quantiles (effective dof varies under cond_cap)
    coverage = ntuple(3) do i
        l = COVERAGE_LEVELS[i]
        count(j -> nees[j] <= quantile(Chisq(dofs[j]), l), 1:n) / n
    end
    μdof = mean(dofs)
    med_ratio = median(nees) / median(Chisq(μdof))
    return CalibrationResult(
        μdof, n, nfail,
        mean(nees), sqrt(2μdof / n), med_ratio,
        coverage, Matrix(cov_emp), sum_pred ./ n
    )
end

"""
    is_calibrated(r::CalibrationResult; z=4.0) -> Bool

Statistical gate: NEES mean within `z` standard errors of `dof` AND every
empirical coverage within `z` binomial standard errors of nominal. `z = 4`
keeps the false-alarm rate negligible at harness trial counts while still
catching a Σ that is wrong by tens of percent.
"""
function is_calibrated(r::CalibrationResult; z::Float64 = 4.0)
    abs(r.nees_mean - r.dof) <= z * r.nees_se || return false
    for (c, l) in zip(r.coverage, COVERAGE_LEVELS)
        se = sqrt(l * (1 - l) / r.ntrials)
        abs(c - l) <= z * se || return false
    end
    return true
end

"""
    noise_ladder(make_trial, rng, ntrials, dof, σs) -> Vector{Pair{Float64,CalibrationResult}}

Run one calibration cell per noise level: `make_trial(σ)` must return a trial
closure. Reports every rung — including the ones past the first-order
breakdown (the first rung failing `is_calibrated` marks it).
"""
noise_ladder(make_trial, rng::AbstractRNG, ntrials::Int, dof::Int, σs) =
    [σ => run_calibration(make_trial(σ), rng, ntrials, dof) for σ in σs]

function format_result(r::CalibrationResult)
    cov = join(
        (
            string(round(Int, 100l), "%:", rpad(round(c; digits = 3), 5))
                for (l, c) in zip(COVERAGE_LEVELS, r.coverage)
        ), "  "
    )
    return string(
        "NEES ", round(r.nees_mean; digits = 3), " (dof ", round(r.dof; digits = 2),
        ", se ", round(r.nees_se; digits = 3), ", med-ratio ",
        round(r.nees_median_ratio; digits = 2), ")  cov[", cov,
        "]  N=", r.ntrials, " div=", r.nfail,
        is_calibrated(r) ? "  CALIBRATED" : "  MISCALIBRATED"
    )
end

