# REPRESENTATIVE SCALE: an ambient covariance is a covariance OF A
# REPRESENTATIVE; the sl(3) chart inherits its anchor's ambient scale, so the
# anchor is unit-Frobenius-normalized first (the epipolar charts pin their own
# ambient scale — ‖skew(t)R‖ = √2, ‖U diag(1,σ,0)Vᵀ‖ = √(1+σ²) — so unitizing
# is a no-op there). g is homogeneous of degree 1 in vec(θ), so the tracked
# solution set and the sensitivity J are anchor-scale invariant; unitizing
# only fixes the CHART-COORDINATE scale convention shared by v and Σ̃_v.
_unit(H::HomographyMat) = HomographyMat{Float64}(Tuple(unit_normalize(H)))

# Damped Newton on g(v, x_fixed) = 0 from `v0` — for an OVERDETERMINED sample
# (more constraints than dof) the damped Gauss–Newton of the whitened-constraint
# (Sampson) estimator: rows whitened per pair by `whitening_factor` of ∂_x g at
# the iterate, the estimator `implicit_covariance`'s sandwich linearizes, and the one it
# reduces to on a square system. Armijo backtracking on the (whitened) residual
# norm (c = 1e-4 — standard Newton globalization; the quadratic phase takes full
# steps and the step-size test converges it). Returns `nothing` on a singular
# (whitened) ∂_v g or a line-search stall.
function _manifold_newton(
        ch, v0::SVector{D, Float64}, cs;
        tol::Float64, maxiter::Int
    ) where {D}
    v = v0
    g = manifold_constraints(ch, v, cs)
    square = length(g) == D
    buf = square ? nothing : similar(g)     # the line search's whitened residual
    for _ in 1:maxiter
        A, W = _newton_system(ch, v, cs, square)
        WA = _whitened(W, A)
        Wg = _whitened(W, g)
        Δ = _newton_increment(WA, Wg, W, Val(D))
        Δ === nothing && return nothing
        # already converged (covers the zero-perturbation residual g ≈ 0,
        # where a strict line-search decrease is impossible at machine level)
        norm(Δ) <= tol * (1 + norm(v)) && return v + Δ
        gnorm = norm(Wg)
        # Gauss–Newton converges to a NONZERO residual: its sufficient decrease is
        # the cost's (Armijo against the predicted ‖W·A·Δ‖²), and a prediction at
        # rounding level is convergence
        pred = W === nothing ? nothing : sum(abs2, WA * Δ)
        pred !== nothing && pred <= 16 * eps() * gnorm^2 && return v + Δ
        α = 1.0
        ok = false
        local vn, gn
        for _ in 1:24
            vn = v + α * Δ
            gn = manifold_constraints(ch, vn, cs)
            if _sufficient_decrease(norm(_whitened!(buf, W, gn)), gnorm, α, pred)
                ok = true
                break
            end
            α /= 2
        end
        ok || return nothing
        v = vn
        g = gn
        α == 1.0 && norm(Δ) <= tol * (1 + norm(v)) && return v
    end
    return nothing
end

# Armijo: Newton's residual norm (zero at the root), the Gauss–Newton cost's
# predicted decrease (c = 1e-4 both).
_sufficient_decrease(gn, g0, α, ::Nothing) = gn <= (1 - 1.0e-4 * α) * g0
_sufficient_decrease(gn, g0, α, pred::Float64) = gn^2 <= g0^2 - 1.0e-4 * α * pred

# The Newton increment Δ of a square system (LU, as always); the whitened
# Gauss–Newton increment of an overdetermined one (pivoted QR, `nothing` below
# numerical rank), from the ALREADY whitened `W·A` and `W·g`.
function _newton_increment(A, g, ::Nothing, ::Val{D}) where {D}
    Flu = lu(A; check = false)
    issuccess(Flu) || return nothing
    return SVector{D, Float64}(-(Flu \ g))
end
function _newton_increment(WA, Wg, W, ::Val{D}) where {D}
    F = qr(WA, ColumnNorm())
    abs(F.R[D, D]) > D * eps() * abs(F.R[1, 1]) || return nothing
    return SVector{D, Float64}(-(F \ Wg))
end

# The Newton system at `v`: ∂_v g, and the per-pair whitening factors L⁻¹ of
# each pair's own ∂_x g block (`nothing` for a square system). One sweep over the
# pairs; the block-diagonal ∂_x g of `constraint_jacobians` is never assembled.
function _newton_system(ch, v, cs, square::Bool)
    square && return first(constraint_jacobians(ch, v, cs)), nothing
    M = retract(ch, v)
    return _whitened_system(ch, M, v, cs, Val(constraint_dim(M)), Val(_measurement_dim(M)))
end
function _whitened_system(ch, M, v, cs, ::Val{dg}, ::Val{nx}) where {dg, nx}
    k = length(cs)
    T = retract_jacobian(ch, v)                              # ambient × D
    A = Matrix{Float64}(undef, dg * k, tangent_size(ch))     # ∂_v g
    W = Vector{SMatrix{dg, dg, Float64, dg * dg}}(undef, k)
    for i in 1:k
        _, Gx, Gθ = cd_pair(M, cs, i)
        A[(dg * (i - 1) + 1):(dg * i), :] = _chart_rows(T, Gθ, Val(dg))
        W[i] = whitening_factor(SMatrix{dg, nx, Float64}(Tuple(Gx)))
    end
    return A, W
end

# The per-pair factors' action on stacked rows (of g, or of ∂_v g); the `!`
# form writes into `out` (and hands `x` back unwhitened when there are none).
_whitened(::Nothing, x) = x
_whitened(W::Vector{<:SMatrix}, x::AbstractVecOrMat) = _whitened!(similar(x, Float64), W, x)
_whitened!(out, ::Nothing, x) = x
function _whitened!(out, W::Vector{<:SMatrix{dg, dg}}, x::AbstractVecOrMat) where {dg}
    for i in eachindex(W)
        rows = (dg * (i - 1) + 1):(dg * i)
        mul!(view(out, rows, :), W[i], view(x, rows, :))
    end
    return out
end

"Linear interpolation between two correspondence sets (data homotopy)."
_lerp_pairs(cs0, cs1, t::Float64) = map((c0, c1) -> _lerp(c0, c1, t), cs0, cs1)

# A two-view correspondence (2-vector endpoints, `Point2` or `SVector`) moves
# both endpoints; a pose correspondence `X => u` moves only its image point —
# the 3D point is exact.
const _Image2 = Union{Point2, StaticVector{2}}
_lerp(c0::Pair{<:_Image2, <:_Image2}, c1::Pair, t::Float64) =
    _lerp_point(c0.first, c1.first, t) => _lerp_point(c0.second, c1.second, t)
_lerp(c0::Pair, c1::Pair, t::Float64) = c0.first => _lerp_point(c0.second, c1.second, t)
_lerp_point(a, b, t::Float64) =
    Point2{Float64}((1 - t) * SVector{2, Float64}(a) + t * SVector{2, Float64}(b))
# A bearing set (an essential matrix's data) moves both bearings, back onto the
# sphere, and their pixel Jacobians `M₁`/`M₂` with them. Only the path's end
# must be exact, and the last stage takes the noisy set itself.
function _lerp_pairs(cs0::Csponds{<:StaticVector{3}, <:StaticVector{3}}, cs1::Csponds, t::Float64)
    mix(a, b) = (1 - t) * a + t * b
    bearing(a, b) = Vec3{Float64}(normalize(mix(SVector{3, Float64}(a), SVector{3, Float64}(b))))
    return withattrs(
        Csponds(bearing.(sources(cs0), sources(cs1)), bearing.(targets(cs0), targets(cs1)));
        M₁ = mix.(cs0.M₁, cs1.M₁), M₂ = mix.(cs0.M₂, cs1.M₂)
    )
end

"""
    track_manifold_solution(ch, cs_clean, cs_noisy;
                         stages=4, tol=1e-11, maxiter=50, min_dt=1/64)
        -> SVector{tangent_size(ch)} | nothing

Damped chart-Newton CONTINUATION of the local constrained solution: the
measurements are moved from `cs_clean` (on the constraint variety — the
anchor of `ch` solves g exactly there) to `cs_noisy` along the linear data
homotopy, each stage solved by damped Newton on g(v, x_t) = 0 warm-started
at the previous stage's solution. The stage size starts at `1/stages` and
is BISECTED adaptively whenever a stage fails to converge (standard
continuation practice — strong constraint curvature shrinks the per-stage
Newton basin). Returns the tracked chart coordinates of the local solution
of g(v, x_noisy) = 0, or `nothing` when a stage still fails at `min_dt` —
the DIVERGENCE event reported by the calibration tables: at that noise
level the perturbation left the continuation radius of this sample's
geometry.
"""
function track_manifold_solution(
        ch, cs_clean::AbstractVector, cs_noisy::AbstractVector;
        stages::Int = 4, tol::Float64 = 1.0e-11,
        maxiter::Int = 50, min_dt::Float64 = 1 / 64
    )
    D = tangent_size(ch)
    v = zero(SVector{D, Float64})
    dt0 = 1.0 / stages
    t = 0.0
    dt = dt0
    while t < 1.0 - 1.0e-12
        tn = min(t + dt, 1.0)
        cs_t = tn >= 1.0 - 1.0e-12 ? cs_noisy : _lerp_pairs(cs_clean, cs_noisy, tn)
        vn = _manifold_newton(ch, v, cs_t; tol = tol, maxiter = maxiter)
        if vn === nothing
            dt /= 2
            dt < min_dt && return nothing
            continue
        end
        v = vn
        t = tn
        dt = min(2 * dt, dt0)
    end
    return v
end

# -----------------------------------------------------------------------------
# Trial builders — continuation-tracking calibration of the chart-domain
# hypothesis covariance (E / F / H / pose). Solver-free by default: θ_gt is the
# exact interpolant of the clean correspondences by construction.
#
# THE HOOKS every trial builder takes, so a consumer plugs its own estimator and
# covariance provider into the same scenes, noise and statistics:
#   npts        — correspondences per trial (default: the minimal count); the
#                 first minimal ones stay stratified, the rest are the
#                 overdetermined set;
#   estimate    — `estimate(ch, cs_noisy) -> model | nothing` (an ambient model:
#                 a 3×3 matrix, or an `EuclideanMap` for a pose), expressed in the
#                 chart by `local_coordinates(ch, ·)`. Default: the unique minimal
#                 solve where the problem has one (H on 4 points), otherwise the
#                 local solution TRACKED from the anchor — Newton on a minimal
#                 sample, the whitened (Sampson) Gauss–Newton on an
#                 overdetermined one;
#   covariance  — `covariance(ch, cs_clean, shapes) -> Σ̃_v | nothing`, unit
#                 scale. Default: `implicit_covariance(ch, cs; Σx)` — the square
#                 solve on a minimal sample, the sandwich (the default
#                 estimator's first-order covariance) on an overdetermined one;
#   error       — how the estimate's error is measured: `:chart` (default), its
#                 chart coordinates; `:ambient`, its displacement from θ_gt in
#                 the ambient space, on the chart's tangent (the scale of a
#                 projective model solved jointly). A first-order covariance
#                 describes the second; the first adds the chart's own
#                 nonlinearity. Use `:ambient` for the fundamental matrix, whose
#                 Bartoli–Sturm chart is strongly nonlinear along its weak
#                 directions (n = 30: chart NEES 10.5–150 over 7, ambient 6.7–7.0).
#                 The sl(3) chart is linear (the two agree); for a rotation the
#                 chart's log coordinates are the geodesic measure.
# `cs` and the shapes are in the trial's working frame (the calibration frame
# for F, calibrated coordinates for E and the pose; for a camera-aware E, pixel
# shapes and bearing correspondences carrying their pixel Jacobians).
# -----------------------------------------------------------------------------

_is_minimal(ch, cs) = length(cs) * constraint_dim(model(ch)) == tangent_size(ch)

function _trial_covariance(covariance, ch, cs, shapes)
    covariance === nothing || return covariance(ch, cs, shapes)
    return implicit_covariance(ch, cs; Σx = shapes)
end

# The estimate as (model, chart coordinates), or `nothing`.
function _trial_estimate(estimate, ch, cs, csn; minimal_solve = nothing)
    solve = estimate !== nothing ? (c -> estimate(ch, c)) :
        (minimal_solve !== nothing && _is_minimal(ch, cs)) ? minimal_solve : nothing
    if solve === nothing
        v = track_manifold_solution(ch, cs, csn)
        v === nothing && return nothing
        return retract(ch, v), v
    end
    θ̂ = solve(csn)
    θ̂ === nothing && return nothing
    v = _chart_coordinates(ch, θ̂)
    any(!isfinite, v) && return nothing
    return θ̂, v
end
# One chart-domain trial on a built scene: the covariance at θ_gt (from the
# clean `cs`) and the estimate (from the noisy `csn`), `nothing` when either
# fails; otherwise the estimate's error and the covariance scaled by σ².
function _chart_trial(estimate, covariance, error, ch, cs, csn, shapes, σ; minimal_solve = nothing)
    Σ̃ = _trial_covariance(covariance, ch, cs, shapes)
    Σ̃ === nothing && return nothing
    est = _trial_estimate(estimate, ch, cs, csn; minimal_solve = minimal_solve)
    est === nothing && return nothing
    return _trial_error(Val(error), ch, est...), σ^2 .* Matrix(Symmetric(Σ̃))
end

_chart_coordinates(ch, θ̂::EuclideanMap) = local_coordinates(ch, θ̂)
_chart_coordinates(ch, θ̂) = local_coordinates(ch, SMatrix{3, 3, Float64, 9}(θ̂))

# The error a trial reports for its estimate θ̂ (chart coordinates v):
#   :chart   — v itself, the estimate's coordinates in the chart at θ_gt;
#   :ambient — the estimate's AMBIENT displacement from θ_gt on the chart's
#              tangent: the least-squares w of s·θ̂ ≈ θ_gt + T·w (T =
#              retract_jacobian at the anchor), a projective model's scale s
#              solved JOINTLY with w (aligning the scale first leaks the
#              mismatch into the weak directions, amplified by T's conditioning);
#              the pseudo-inverse drops gauge directions. The first-order
#              coordinates a covariance pushed to the ambient space describes,
#              free of the chart's own nonlinearity along its weak directions.
_trial_error(::Val{:chart}, ch, θ̂, v) = Vector(v)
function _trial_error(::Val{:ambient}, ch, θ̂, v)
    m0 = Vector(_ambient_coordinates(model(ch)))
    m̂ = Vector(_ambient_coordinates(θ̂))
    T = Matrix(retract_jacobian(ch))
    θ̂ isa EuclideanMap && return pinv(T) * (m̂ - m0)
    ws = pinv(hcat(T, -m̂)) * (-m0)                 # [T  −θ̂]·[w; s] ≈ −θ_gt
    return ws[1:size(T, 2)]
end

_homography_4pt(csn) = homography_4pt(
    csn[1].first, csn[2].first, csn[3].first, csn[4].first,
    csn[1].second, csn[2].second, csn[3].second, csn[4].second
)

"""
    homography_trial(; σ, regime=:generic, aniso=false, img2_scale=1.0,
                     npts=4, estimate=nothing, covariance=nothing)

Chart-domain calibration trial for the 8-dof sl(3) homography chart
covariance: base 4-point sample with θ_gt as its exact interpolant, known
per-point perturbation, then the UNIQUE minimal solution of the perturbed
sample (the 4-point problem is single-valued — no tracking device needed),
expressed in the chart anchored at θ_gt and compared against the
implicit-function covariance J·Σ̃_x·Jᵀ at θ_gt. `npts`, `estimate`, `covariance`:
the hooks (see the section header).
"""
function homography_trial(;
        σ::Float64, regime::Symbol = :generic,
        aniso::Bool = false, img2_scale::Float64 = 1.0,
        npts::Int = 4, estimate = nothing, covariance = nothing, error::Symbol = :chart
    )
    function trial(rng)
        H, cs = sample_homography_scene(rng; regime = regime, npts = npts)
        shapes = make_point_covs(rng, npts; aniso = aniso, img2_scale = img2_scale)
        csn = perturb_pairs(rng, cs, σ, shapes)
        ch = minimal_manifold(_unit(H))
        return _chart_trial(
            estimate, covariance, error, ch, cs, csn, shapes, σ;
            minimal_solve = _homography_4pt
        )
    end
    return trial
end

"""
Calibration frame for the F cells: pixel coordinates scaled by `s = 1/25`
about the principal point. The Bartoli–Sturm orthonormal chart is
near-GAUGE at both natural frames — raw pixels drive σ₂/σ₁ → ~1e-4
(U/V near-co-rotation gauge; chart-coordinate calibration is numerically
meaningless there — REPORTED as a finding by the pixel-frame driver cell),
and K-normalized coordinates drive σ → 1 exactly (F → E, the near-essential
gauge Bartoli–Sturm §5.1.4). s = 1/25 puts the scene family's σ₂/σ₁ in
~[0.04, 0.95] (median 0.22): generically mid-gauge.
"""
const F_NORM_SCALE = 1 / 25

"Similarity u_px → u_cal for the F calibration frame (3×3 homogeneous)."
fundmat_norm_xform(; s::Float64 = F_NORM_SCALE, c::Float64 = 250.0) =
    SMatrix{3, 3, Float64, 9}(s, 0, 0, 0, s, 0, -c * s, -c * s, 1)

"""
    fundmat_trial(; σ, regime=:generic, aniso=false, frame=:calibration,
                  img2_scale=1.0, f=600.0, npts=7, estimate=nothing, covariance=nothing)

Continuation-tracking calibration trial for the Bartoli–Sturm 7-dof F chart
covariance. `frame = :calibration` (default) runs tracking + provider + chart
NEES in the mid-gauge frame [`fundmat_norm_xform`](@ref) with noise σ·s;
`frame = :pixel` runs raw — kept to DOCUMENT the pixel-frame chart degeneracy
(expected miscalibrated at every σ). `npts`, `estimate`, `covariance`: the hooks
(see the section header); `f` the focal length of the scene.
"""
function fundmat_trial(;
        σ::Float64, regime::Symbol = :generic, aniso::Bool = false,
        frame::Symbol = :calibration, img2_scale::Float64 = 1.0, f::Float64 = 600.0,
        npts::Int = 7, estimate = nothing, covariance = nothing, error::Symbol = :chart
    )
    T = fundmat_norm_xform()
    Tit = inv(T)'
    function trial(rng)
        _, _, F, _, cs_px, _ = sample_twoview_scene(rng, npts; regime = regime, f = f)
        local Fn, cs, σn
        if frame === :calibration
            Fn = FundMat{Float64}(Tuple(Tit * SMatrix{3, 3, Float64, 9}(F) * inv(T)))
            cs = [
                Point2{Float64}(to_euclidean(T * to_affine(c.first))) =>
                    Point2{Float64}(to_euclidean(T * to_affine(c.second)))
                    for c in cs_px
            ]
            σn = σ * F_NORM_SCALE
        else
            Fn, cs, σn = F, cs_px, σ
        end
        shapes = make_point_covs(rng, npts; aniso = aniso, img2_scale = img2_scale)
        csn = perturb_pairs(rng, cs, σn, shapes)
        ch = minimal_manifold(Fn)
        return _chart_trial(estimate, covariance, error, ch, cs, csn, shapes, σn)
    end
    return trial
end

# -----------------------------------------------------------------------------
# Bearing correspondences for the CAMERA-AWARE E trials
# -----------------------------------------------------------------------------
#
# The harness's own frame assumption, made explicit. The calibrated-2-vector
# trials below are correct and stay the default, but the harness's E trials
# hand an E consumer calibrated z = 1 points, while the solvers take bearings.
# A consumer whose E problem takes bearings cannot adapt
# LOCALLY, and that is the point: the harness's σ builds the point covariances
# the calibration test is ABOUT, so converting the data without converting σ
# would put the noise model and the data in different frames INSIDE the
# instrument that measures whether covariances are calibrated.
#
# So the camera-aware path moves BOTH together: pixel data, pixel σ, pixel
# shapes, and the geometry carried to bearings through
# `backproject_with_jacobian` — whose Jacobians ride as the `M₁`/`M₂` columns
# that put a consumer's residual back in pixels. That whitening is the one the
# B8 Monte-Carlo cells validated (NEES 0.999–1.016 against a predicted SE of
# 0.010), so the harness and the thing it measures agree by construction. The
# chart machinery reads the same columns (`cd_pair` on a bearing set takes the
# tangent form), so the default `estimate` and `covariance` run on bearings too.

# Pixel pairs → bearing csponds carrying their pixel Jacobians.
function _bearing_csponds(cam1, cam2, cs_px)
    k = length(cs_px)
    b1 = Vector{Vec3{Float64}}(undef, k); b2 = Vector{Vec3{Float64}}(undef, k)
    J1 = Vector{SMatrix{3, 2, Float64, 6}}(undef, k)
    J2 = Vector{SMatrix{3, 2, Float64, 6}}(undef, k)
    for i in 1:k
        u = cs_px[i].first; v = cs_px[i].second
        f₁, M₁ = backproject_with_jacobian(cam1, SVector{2, Float64}(u[1], u[2]))
        f₂, M₂ = backproject_with_jacobian(cam2, SVector{2, Float64}(v[1], v[2]))
        b1[i] = Vec3{Float64}(f₁); b2[i] = Vec3{Float64}(f₂)
        J1[i] = SMatrix{3, 2, Float64, 6}(M₁); J2[i] = SMatrix{3, 2, Float64, 6}(M₂)
    end
    return withattrs(Csponds(b1, b2); M₁ = J1, M₂ = J2)
end

# The calibrated (z = 1) scene points projected through two REAL cameras. The
# scene's own `f` fixes view 1's pixel frame; view 2 is re-projected, so its
# field is the second camera's and is not re-checked against the generator's
# image bounds — a backprojection is defined everywhere a pinhole is.
function _pixel_pairs(cam1, cam2, cs_nm)
    return [
        Point2{Float64}(project(cam1, SVector{3, Float64}(c.first[1], c.first[2], 1.0))) =>
            Point2{Float64}(project(cam2, SVector{3, Float64}(c.second[1], c.second[2], 1.0)))
            for c in cs_nm
    ]
end

"""
    essential_trial(; σ_px, f=600.0, regime=:generic, aniso=false, img2_scale=1.0,
                    npts=5, estimate=nothing, covariance=nothing, cameras=nothing)

Continuation-tracking calibration trial for the 5-dof so(3)⊕T_tS² essential
chart covariance.

**Default (`cameras = nothing`)**: works in K-NORMALIZED coordinates, pixel
noise `σ_px` entering as `σ = σ_px/f`, as the F and H trials do.

**Camera-aware (`cameras = (cam1, cam2)`)**: the scene is projected through two
real [`CameraModel`](@ref)s, perturbed in PIXELS with `σ_px` itself, and handed
to the estimate and the covariance as BEARING correspondences carrying the
`M₁`/`M₂` pixel Jacobians from [`backproject_with_jacobian`](@ref) — what an
essential-matrix problem takes. The default estimate and covariance read those
columns (the tangent form of `constraint_with_jacobians`), so the hooks are
optional here as everywhere. The returned covariance is scaled by `σ_px²`, so
the noise model moves into the same frame as the data rather than being left
behind in calibrated units.

**Use two DIFFERENT focal lengths.** A per-view `M₁`/`M₂` swap is nearly
norm-preserving: measured, it moves a residual by 1.8% at f = 1200/600 but only
0.19% at equal focals, where it would hide inside anything one would call
noise.

`npts`, `estimate`, `covariance`: the hooks (see the section header).
"""
function essential_trial(;
        σ_px::Float64, f::Float64 = 600.0,
        regime::Symbol = :generic, aniso::Bool = false,
        img2_scale::Float64 = 1.0,
        npts::Int = 5, estimate = nothing, covariance = nothing, error::Symbol = :chart,
        cameras = nothing
    )
    σ = cameras === nothing ? σ_px / f : σ_px    # the frame the data is in
    function trial(rng)
        _, _, _, E, _, cs_nm = sample_twoview_scene(rng, npts; regime = regime, f = f)
        cs = cameras === nothing ? cs_nm : _pixel_pairs(cameras..., cs_nm)
        shapes = make_point_covs(rng, npts; aniso = aniso, img2_scale = img2_scale)
        csn = perturb_pairs(rng, cs, σ, shapes)
        ch = minimal_manifold(E)
        cameras === nothing && return _chart_trial(estimate, covariance, error, ch, cs, csn, shapes, σ)
        # bearings: M at the true pixels for the truth, at the perturbed ones for the data
        return _chart_trial(
            estimate, covariance, error, ch,
            _bearing_csponds(cameras..., cs), _bearing_csponds(cameras..., csn), shapes, σ
        )
    end
    return trial
end

