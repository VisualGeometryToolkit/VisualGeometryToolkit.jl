p3p_trial(; σ_px::Float64, kwargs...) = pnp_trial(; σ_px = σ_px, npts = 3, kwargs...)

"""
    reprojection_trial(; σ_px, npts=3, f=600.0, c=250.0, aniso=false, level=0.95,
                       estimate=nothing, covariance=nothing)

Criminisi-protocol output-domain trial for the pose: estimate the pose from
`npts` noisy image points (as [`pnp_trial`](@ref)), then reproject a HELD-OUT
3D point and test its reprojection against its own noisy observation, inside the
first-order `level` ellipse composing the model term (`J·σ²Σ̃_v·Jᵀ`, `J` the
reprojection's derivative in the pose chart at θ_gt) with the query term
(`σ²Σ_q`). Returns `(contained::Bool,)` or `nothing` (divergence / degenerate
anchor).
"""
function reprojection_trial(;
        σ_px::Float64, npts::Int = 3, f::Float64 = 600.0, c::Float64 = 250.0,
        aniso::Bool = false, level::Float64 = 0.95,
        estimate = nothing, covariance = nothing
    )
    σ = σ_px / f
    k2 = quantile(Chisq(2), level)
    function trial(rng)
        pose, csall, _ = sample_pose_scene(rng, npts + 1; f = f, c = c)
        cs = csall[1:npts]
        Xq, uq = csall[end]
        shapes = [make_query_cov(rng; aniso = aniso) for _ in 1:npts]
        Σq = make_query_cov(rng; aniso = aniso)
        csn = perturb_pairs(rng, cs, σ, shapes)
        δq = _gaussian_offset(rng, σ, Σq)
        ch = LeftRigidManifold6(pose)
        Σ̃v = _trial_covariance(covariance, ch, cs, shapes)
        Σ̃v === nothing && return nothing
        est = _trial_estimate(estimate, ch, cs, csn)
        est === nothing && return nothing
        p̂ = est[1]
        X̂c = SMatrix{3, 3, Float64, 9}(p̂.R) * Xq + SVector{3, Float64}(p̂.t)
        d = PerspectiveMap()(X̂c) - SVector(uq[1] + δq[1], uq[2] + δq[2])
        Xc = SMatrix{3, 3, Float64, 9}(pose.R) * Xq + SVector{3, Float64}(pose.t)
        J = transform_deriv(PerspectiveMap(), Xc) * action_jacobian(ch, Xq)       # 2×6
        Σout = σ^2 .* (Matrix(J * Σ̃v * J') + Matrix(Σq))
        inside = _mahalanobis_inside(d, Σout, k2)
        inside === nothing && return nothing
        return (inside,)
    end
    return trial
end

# -----------------------------------------------------------------------------
# Second-order propagated moments of an output functional — the thesis's
# first-order vs second-order vs Monte-Carlo goodness triple (the
# second-order rung shows the linearization is sufficient wherever the three
# agree).
# -----------------------------------------------------------------------------

"""
    second_order_moments(res, out, D, x0, q0, Σδ) -> (Σ1, μ2, Σ2)

First- and second-order propagated moments of the output functional
`out([v; q])` under the implicitly defined chart solution `v(x)` of
`res([v; x]) = 0` (D equations, `res([0; x0]) = 0` at the anchor), with
Gaussian input `δ = (x − x0, q − q0) ~ N(0, Σδ)`.

Returns the first-order output covariance `Σ1 = J·Σδ·Jᵀ`, the second-order
mean shift `μ2[c] = ½·tr(Q_c·Σδ)`, and the second-order covariance
`Σ2[c,d] = Σ1[c,d] + ½·tr(Q_c·Σδ·Q_d·Σδ)` (Gaussian fourth-moment identity),
where `Q_c` is the full second derivative of output component `c` with
respect to `δ`, assembled from the implicit first/second derivatives of
`v(x)` (implicit function theorem, differentiated twice) and the ForwardDiff
Hessians of `res` and `out`.
"""
function second_order_moments(
        res, out, D::Int, x0::AbstractVector,
        q0::AbstractVector, Σδ::AbstractMatrix
    )
    nx = length(x0)
    nq = length(q0)
    z0 = vcat(zeros(D), Vector{Float64}(x0))
    JF = ForwardDiff.jacobian(res, z0)                     # D × (D+nx)
    Amat = JF[:, 1:D]
    Bmat = JF[:, (D + 1):end]
    vx = -(Amat \ Bmat)                                    # D × nx
    w0 = vcat(zeros(D), Vector{Float64}(q0))
    Jφ = ForwardDiff.jacobian(out, w0)                     # m × (D+nq)
    φv = Jφ[:, 1:D]
    φq = Jφ[:, (D + 1):end]
    m = size(Jφ, 1)
    J = hcat(φv * vx, φq)                                  # m × (nx+nq)
    Σ1 = Matrix(Symmetric(J * Matrix(Σδ) * J'))
    # implicit second derivative of v(x):  v_xx[r] = −Σ_s A⁻¹[r,s]·(Lᵀ H_s L)
    Lz = vcat(vx, Matrix(1.0I, nx, nx))                    # (D+nx) × nx
    Hres = _component_hessians(res, z0, D)                 # D × (D+nx) × (D+nx)
    Mr = [Lz' * Hres[r, :, :] * Lz for r in 1:D]
    Ainv = inv(Amat)
    vxx = [-sum(Ainv[r, s] .* Mr[s] for s in 1:D) for r in 1:D]
    W = [vx zeros(D, nq); zeros(nq, nx) Matrix(1.0I, nq, nq)]  # (D+nq) × (nx+nq)
    Hout = _component_hessians(out, w0, m)                 # m × (D+nq) × (D+nq)
    Σs = Matrix(Σδ)
    P = Vector{Matrix{Float64}}(undef, m)                  # P_c = Q_c·Σδ
    for c in 1:m
        Qc = W' * Hout[c, :, :] * W
        Qc[1:nx, 1:nx] .+= sum(φv[c, r] .* vxx[r] for r in 1:D)
        P[c] = Matrix(Symmetric(Qc)) * Σs
    end
    μ2 = [0.5 * tr(P[c]) for c in 1:m]
    Σ2 = copy(Σ1)
    for c in 1:m, d in 1:m
        Σ2[c, d] += 0.5 * sum(P[c] .* transpose(P[d]))     # tr(P_c·P_d)
    end
    return Σ1, μ2, Matrix(Symmetric(Σ2))
end

# The Hessians of every output component of `f` at `z0`, from one nested
# ForwardDiff evaluation: `H[r, j, k] = ∂²f_r/∂z_j∂z_k` (`n` outputs).
function _component_hessians(f, z0, n::Int)
    N = length(z0)
    return reshape(ForwardDiff.jacobian(z -> ForwardDiff.jacobian(f, z), z0), n, N, N)
end

