"""
    sample_homography_scene(rng; regime=:generic, npts=4) -> (H::HomographyMat, cs)

Ground-truth homography + `npts` source points (the first 4 well-spread, the
rest uniform) in a nominal 500×500 image. Regimes: `:generic` (strong
projective part), `:near_affine` (projective row ~1e-8 — the near-degenerate
regime for the 8-dof chart's projective directions).
"""
function sample_homography_scene(
        rng::AbstractRNG; regime::Symbol = :generic,
        npts::Int = 4
    )
    θ = 0.5 * randn(rng)
    s = 0.8 + 0.4 * rand(rng)
    A = s * SMatrix{2, 2, Float64, 4}(cos(θ), sin(θ), -sin(θ), cos(θ)) +
        0.1 * SMatrix{2, 2, Float64, 4}(randn(rng, 4)...)
    t = 50 * SVector{2}(randn(rng, 2))
    p = regime === :near_affine ? 1.0e-8 * SVector{2}(randn(rng, 2)) :
        8.0e-4 * SVector{2}(randn(rng, 2))
    H = HomographyMat{Float64}(
        A[1, 1], A[2, 1], p[1],
        A[1, 2], A[2, 2], p[2],
        t[1], t[2], 1.0
    )
    base = (
        Point2{Float64}(100, 100), Point2{Float64}(400, 120),
        Point2{Float64}(380, 400), Point2{Float64}(120, 380),
    )
    srcs = [
        i <= 4 ?
            Point2{Float64}(base[i][1] + 30randn(rng), base[i][2] + 30randn(rng)) :
            Point2{Float64}(50 + 400rand(rng), 50 + 400rand(rng))
            for i in 1:npts
    ]
    Hm = SMatrix{3, 3, Float64, 9}(H)
    cs = [u => Point2{Float64}(to_euclidean(Hm * to_affine(u))) for u in srcs]
    return H, cs
end

"""
    sample_twoview_scene(rng, k; regime=:generic, f=600.0, c=250.0)
        -> (R, t, F::FundMat, E::EssentialMat, cs_px, cs_norm, cs_bear)

Two calibrated views (shared K = diag(f, f, 1) + principal point c) observing
`k` random 3D points; returns pixel correspondences (for F), K-normalized
GNOMONIC correspondences, and UNIT BEARING correspondences (`Vec3` each side,
for E).

`cs_bear` is the calibrated currency of this stack: E, relative pose and PnP
act on bearings, never on the z = 1 chart. `cs_norm` is the chart and is kept
only for the Monte-Carlo cells that have not yet moved to the tangent Sampson;
those cells migrate with the E gates, and it goes with them. New code should
take `cs_bear`.

Appended rather than substituted on purpose: Julia's destructuring ignores
trailing elements, so every existing six-way call site keeps working and
nothing silently changes meaning under a positional unpack. Regimes:
`:generic` — baseline 1, depths 4–8, rotation ~10°;
`:short_baseline` — ‖t‖ = 0.02 vs depths 4–8 (near-degenerate E);
`:near_planar` — depth variation 1e-3 about a plane (near-degenerate F);
`:forward` — translation along camera 1's optical axis (`t ∝ (0.1·n₁, 0.1·n₂, ±1)`),
both epipoles inside the `2c × 2c` image (geometries resampled until they are),
and a point whose PARALLAX — its displacement from the rotation-only image
`π(K·R·K⁻¹·ũ₁)` — is under 1 px resampled: near the epipole a correspondence
carries no epipolar information, and a trial built on one fails for reasons that
are not the covariance's.
"""
function sample_twoview_scene(
        rng::AbstractRNG, k::Int; regime::Symbol = :generic,
        f::Float64 = 600.0, c::Float64 = 250.0
    )
    # SPATIAL STRATIFICATION of the minimal sample: one point per cell of a
    # 3×3 image grid (shuffled). Unstratified uniform sampling produces
    # clustered / quasi-degenerate minimal samples for a large fraction of
    # draws, and their tracked solutions leave the first-order regime at
    # sub-pixel noise — that failure mode is a property of DEGENERATE
    # SAMPLES, not of the covariance propagation under test. Stratified
    # samples are the RANSAC-favorable configurations; the noise ladder still
    # locates the honest first-order breakdown for them. Geometries whose
    # disparity makes a cell unsatisfiable are resampled wholesale.
    K = _pixel_K(f, f, (c, c))
    Km = AffineMap(K)             # normalized (z = 1) → pixel
    Kinv = inv(Km)                # pixel → normalized
    for _ in 1:200   # geometry attempts
        R = RotMatrix(Rotations.AngleAxis(0.17 + 0.05 * randn(rng), normalize(randn(rng, 3))...))
        baselen = regime === :short_baseline ? 0.02 : 1.0
        t = if regime === :forward
            Vec3{Float64}(normalize(SVector(0.1 * randn(rng), 0.1 * randn(rng), rand(rng, (-1.0, 1.0)))))
        else
            baselen * Vec3{Float64}(normalize(SVector{3}(randn(rng, 3))))
        end
        regime === :forward && !_epipoles_inside(R, t, Km, c) && continue
        E = EssentialMat(SMatrix{3, 3, Float64, 9}(R), t)
        F = FundMat(E, K, K)
        cs_px = Vector{Pair{Point2{Float64}, Point2{Float64}}}(undef, k)
        cs_nm = Vector{Pair{Point2{Float64}, Point2{Float64}}}(undef, k)
        cs_bear = Vector{Pair{Vec3{Float64}, Vec3{Float64}}}(undef, k)
        # first ≤9 points stratified (one per grid cell); extras uniform cells
        cells = k <= 9 ? Random.randperm(rng, 9)[1:k] :
            vcat(Random.randperm(rng, 9), rand(rng, 1:9, k - 9))
        ok = true
        for i in 1:k
            cx, cy = (cells[i] - 1) % 3, (cells[i] - 1) ÷ 3
            w = 2c / 3
            placed = false
            for _ in 1:40   # per-point attempts within the cell
                u1t = SVector(
                    (cx + 0.1 + 0.8 * rand(rng)) * w,
                    (cy + 0.1 + 0.8 * rand(rng)) * w
                )
                d = Kinv(u1t)                                   # cam-1 ray (z = 1)
                z = if regime === :near_planar
                    # plane z = 6 + 0.4x + 0.3y with X = z·(dx, dy, 1); 1e-3 jitter
                    6 / max(1 - 0.4 * d[1] - 0.3 * d[2], 0.2) + 1.0e-3 * randn(rng)
                else
                    4 + 4 * rand(rng)
                end
                X = SVector{3}(z * d[1], z * d[2], z)
                X2 = SMatrix{3, 3, Float64, 9}(R) * X + SVector{3}(t)
                X2[3] > 0.1 || continue
                x2 = PerspectiveMap()(X2)
                u2 = Km(x2)
                all(p -> 0 < p < 2c, u2) || continue
                regime === :forward && _parallax(R, d, u2, Km) < 1.0 && continue
                cs_px[i] = Point2{Float64}(u1t...) => Point2{Float64}(u2...)
                cs_nm[i] = Point2{Float64}(d...) => Point2{Float64}(x2...)
                cs_bear[i] = Vec3{Float64}(normalize(SVector(d[1], d[2], 1.0))) =>
                    Vec3{Float64}(normalize(SVector(x2[1], x2[2], 1.0)))
                placed = true
                break
            end
            placed || (ok = false; break)
        end
        ok && return R, t, F, E, cs_px, cs_nm, cs_bear
    end
    error("sample_twoview_scene: no satisfiable geometry in 200 attempts")
end

# Both epipoles (camera 2's centre −Rᵀt seen from camera 1, camera 1's centre t
# seen from camera 2) inside the 2c × 2c image.
function _epipoles_inside(R, t, Km, c)
    inside(p) = p[3] != 0 && all(q -> 0 < q < 2c, Km(PerspectiveMap()(p)))
    return inside(-(SMatrix{3, 3, Float64, 9}(R)' * SVector{3, Float64}(t))) && inside(SVector{3, Float64}(t))
end

# The translational displacement of a correspondence in image 2 (px): from the
# image `π(K·R·d̃)` the point would have at infinity.
function _parallax(R, d, u2, Km)
    w = SMatrix{3, 3, Float64, 9}(R) * SVector(d[1], d[2], 1.0)
    return norm(Km(PerspectiveMap()(w)) - u2)
end

"""
    sample_pose_scene(rng, n; f = 600.0, c = 250.0) -> (pose::EuclideanMap{3}, cs_nm, cs_px)

A world→camera pose and `n` world points imaged by `K = [f 0 c; 0 f c; 0 0 1]`:
the first `≤ 9` points one per cell of a 3×3 grid over the `2c × 2c` image (as
[`sample_twoview_scene`](@ref) stratifies, and for the same reason), depths 4–8,
the rotation uniform. `cs_nm` pairs `X => u` with `u` calibrated (`K⁻¹`), `cs_px`
with `u` in pixels. `f` sets the field of view: `f = 2000` is narrow (14° at
`c = 250`), `f = 150` wide (118°).
"""
function sample_pose_scene(rng::AbstractRNG, n::Int; f::Float64 = 600.0, c::Float64 = 250.0)
    R = RotMatrix(Rotations.AngleAxis(π * rand(rng), normalize(randn(rng, 3))...))
    t = Vec3{Float64}(randn(rng, 3))
    pose = EuclideanMap(R, t)
    Rm = SMatrix{3, 3, Float64, 9}(R)
    cells = n <= 9 ? randperm(rng, 9)[1:n] : vcat(randperm(rng, 9), rand(rng, 1:9, n - 9))
    w = 2c / 3
    cs_nm = Vector{Pair{SVector{3, Float64}, Point2{Float64}}}(undef, n)
    cs_px = Vector{Pair{SVector{3, Float64}, Point2{Float64}}}(undef, n)
    for i in 1:n
        cx, cy = (cells[i] - 1) % 3, (cells[i] - 1) ÷ 3
        u = SVector((cx + 0.1 + 0.8 * rand(rng)) * w, (cy + 0.1 + 0.8 * rand(rng)) * w)
        d = (u .- c) ./ f
        Xc = (4 + 4 * rand(rng)) * SVector(d[1], d[2], 1.0)
        X = Rm' * (Xc - SVector{3, Float64}(t))
        cs_nm[i] = X => Point2{Float64}(d[1], d[2])
        cs_px[i] = X => Point2{Float64}(u[1], u[2])
    end
    return pose, cs_nm, cs_px
end

