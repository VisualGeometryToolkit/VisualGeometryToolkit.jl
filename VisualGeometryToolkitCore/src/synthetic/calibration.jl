"""
    make_point_covs(rng, k; aniso=false, img2_scale=1.0) -> Vector{SMatrix{4,4}}

Unit-scale 4×4 covariance shapes, one per correspondence, block-diagonal over
the TWO endpoint slots — noise is injected in BOTH images, each endpoint with
its own independent 2×2 covariance (the real-data structure: per-endpoint
precision, e.g. RoMa matcher covariances). `aniso=true` draws per-ENDPOINT
rotated anisotropic 2×2 blocks with trace 2, drawn INDEPENDENTLY for the two
endpoints (so the two images' covariances differ; trace 2 keeps the total
variance of I₂ and σ retains its meaning); `aniso=false` returns isotropic
blocks. `img2_scale` multiplies the image-2 endpoint's standard deviation
(e.g. `img2_scale = 3` → σ₂ = 3σ₁, the unequal-image cells).
"""
function make_point_covs(
        rng::AbstractRNG, k::Int; aniso::Bool = false,
        img2_scale::Float64 = 1.0
    )
    mk2 = function ()
        aniso || return SMatrix{2, 2, Float64, 4}(1, 0, 0, 1)
        φ = 2π * rand(rng)
        ratio = 0.2 + 0.8 * rand(rng)          # λ₂/λ₁ ∈ [0.2, 1.0]
        λ1 = 2 / (1 + ratio); λ2 = 2 - λ1      # trace = 2
        R = SMatrix{2, 2, Float64, 4}(cos(φ), sin(φ), -sin(φ), cos(φ))
        return R * SMatrix{2, 2, Float64, 4}(λ1, 0, 0, λ2) * R'
    end
    s2 = img2_scale^2
    return [
        SMatrix{4, 4, Float64, 16}([mk2() zeros(SMatrix{2, 2, Float64, 4}); zeros(SMatrix{2, 2, Float64, 4}) s2 * mk2()])
            for _ in 1:k
    ]
end

"""
    make_query_cov(rng; aniso=false) -> SMatrix{2,2}

Unit-scale covariance shape for the QUERY point of the output-domain cells
(trace-2 rotated-anisotropic when `aniso`, else I₂) — the measurement-point
noise of the Criminisi Table 4.1 protocol.
"""
function make_query_cov(rng::AbstractRNG; aniso::Bool = false)
    aniso || return SMatrix{2, 2, Float64, 4}(1, 0, 0, 1)
    φ = 2π * rand(rng)
    ratio = 0.2 + 0.8 * rand(rng)
    λ1 = 2 / (1 + ratio); λ2 = 2 - λ1
    R = SMatrix{2, 2, Float64, 4}(cos(φ), sin(φ), -sin(φ), cos(φ))
    return R * SMatrix{2, 2, Float64, 4}(λ1, 0, 0, λ2) * R'
end

"""
    perturb_pairs(rng, cs, σ, shapes) -> Vector{Pair}

Add `δ ~ N(0, σ²·shapes[i])` to each correspondence: to both endpoints of a
two-view pair (4×4 shapes), or to the image point of a pose correspondence
`X => u` (2×2 shapes; the 3D point is exact).
"""
function perturb_pairs(rng::AbstractRNG, cs, σ::Float64, shapes)
    out = similar(cs)
    for i in eachindex(cs)
        out[i] = _perturb(rng, cs[i], σ, shapes[i])
    end
    return out
end
function _perturb(rng::AbstractRNG, c::Pair, σ::Float64, shape::StaticMatrix{4, 4})
    δ = _gaussian_offset(rng, σ, shape)
    u, v = c.first, c.second
    return Point2{Float64}(u[1] + δ[1], u[2] + δ[2]) => Point2{Float64}(v[1] + δ[3], v[2] + δ[4])
end
function _perturb(rng::AbstractRNG, c::Pair, σ::Float64, shape::StaticMatrix{2, 2})
    δ = _gaussian_offset(rng, σ, shape)
    return c.first => Point2{Float64}(c.second[1] + δ[1], c.second[2] + δ[2])
end

# A draw δ ~ N(0, σ²Σ): σ·L·z with Σ = L·Lᵀ and z one `randn` draw of size(Σ, 1).
_gaussian_offset(rng::AbstractRNG, σ::Float64, Σ) =
    σ * (cholesky(Symmetric(Matrix(Σ))).L * randn(rng, size(Σ, 1)))

# Whether `d` lies inside the Mahalanobis ellipse `dᵀΣ⁻¹d ≤ k2`; `nothing` when
# Σ is not positive definite.
function _mahalanobis_inside(d, Σ, k2)
    F = cholesky(Symmetric(Σ); check = false)
    issuccess(F) || return nothing
    return dot(d, F \ d) <= k2
end

