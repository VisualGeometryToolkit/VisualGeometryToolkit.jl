# OUTPUT-DOMAIN calibration — the headline validation (Criminisi, Accurate
# Visual Metrology from Single and Multiple Uncalibrated Images, §4.3.3,
# Table 4.1): Monte Carlo through the OUTPUT functional as the goodness test
# of the first-order analytics, with noise in BOTH the computation
# correspondences (both images, per-endpoint covariances) and the query
# point. H: transferred-point scatter vs the first-order ellipse.
# E / F: epipolar-line family vs the Hartley–Zisserman envelope band.
# The analytic side composes the MODEL covariance term (pushed ambient
# hypothesis covariance) with the QUERY covariance term.
# -----------------------------------------------------------------------------

"""
Result of one output-domain containment cell: `rates[i]` is the empirical
containment fraction of statistic `i` (H: the 95% transfer ellipse;
E/F: [pointwise χ²₁ band, whole-line χ²₂ band]); `nfail` is the
divergence/degeneracy count.
"""
struct ContainmentResult
    ntrials::Int
    nfail::Int
    rates::Vector{Float64}
end

"""
    run_containment(trial, rng, ntrials) -> ContainmentResult

Aggregate `ntrials` output-domain MC trials of
`trial(rng) -> nothing | NTuple{K,Bool}` (contained / not, per statistic).
"""
function run_containment(trial, rng::AbstractRNG, ntrials::Int)
    counts = Int[]
    n = 0
    nfail = 0
    for _ in 1:ntrials
        out = trial(rng)
        if out === nothing
            nfail += 1
            continue
        end
        isempty(counts) && (counts = zeros(Int, length(out)))
        for i in eachindex(counts)
            counts[i] += out[i]
        end
        n += 1
    end
    n == 0 && error("run_containment: every trial failed")
    return ContainmentResult(n, nfail, counts ./ n)
end

"""
    containment_nominal(r, i; level=0.95, z=4.0) -> Bool

Binomial gate: statistic `i`'s empirical containment within `z` binomial
standard errors of `level`.
"""
containment_nominal(
    r::ContainmentResult, i::Int; level::Float64 = 0.95,
    z::Float64 = 4.0
) =
    abs(r.rates[i] - level) <= z * sqrt(level * (1 - level) / r.ntrials)

"""
    h_transfer_trial(; σ, regime=:generic, aniso=false, img2_scale=1.0,
                     level=0.95, npts=4, estimate=nothing, covariance=nothing)

Criminisi Table 4.1 for the homography, containment form: per trial,
perturb the 4 computation correspondences IN BOTH IMAGES (known per-endpoint
covariances), compute the unique minimal H of the perturbed sample, perturb a
query point, transfer it, and test the transferred point against the
first-order `level` ellipse whose covariance composes the model term
(`transform_deriv_params(H, x)` propagating the hypothesis covariance at θ_gt,
transported to the ambient space) with the
query term (`J_x·σ²Σ_q·J_xᵀ`). Returns `(contained::Bool,)` or `nothing`
(degenerate solve). `npts`, `estimate`, `covariance`: the hooks (see the
chart-domain section header).
"""
function h_transfer_trial(;
        σ::Float64, regime::Symbol = :generic,
        aniso::Bool = false, img2_scale::Float64 = 1.0,
        level::Float64 = 0.95,
        npts::Int = 4, estimate = nothing, covariance = nothing
    )
    k2 = quantile(Chisq(2), level)
    function trial(rng)
        H, cs = sample_homography_scene(rng; regime = regime, npts = npts)
        shapes = make_point_covs(rng, npts; aniso = aniso, img2_scale = img2_scale)
        x0 = Point2{Float64}(50 + 400 * rand(rng), 50 + 400 * rand(rng))
        Σq = make_query_cov(rng; aniso = aniso)
        csn = perturb_pairs(rng, cs, σ, shapes)
        δq = _gaussian_offset(rng, σ, Σq)
        ch = minimal_manifold(_unit(H))
        Σ̃v = _trial_covariance(covariance, ch, cs, shapes)
        Σ̃v === nothing && return nothing
        est = _trial_estimate(estimate, ch, cs, csn; minimal_solve = _homography_4pt)
        est === nothing && return nothing
        Ĥm = SMatrix{3, 3, Float64, 9}(est[1])
        x̃q = SVector{3, Float64}(x0[1] + δq[1], x0[2] + δq[2], 1.0)
        X̂ = to_euclidean(Ĥm * x̃q)
        Hu = SMatrix{3, 3, Float64, 9}(Tuple(model(ch)))
        x̃0 = SVector{3, Float64}(x0[1], x0[2], 1.0)
        w = Hu * x̃0
        X0 = SVector{2, Float64}(PerspectiveMap()(w))
        # first-order output covariance: model term + query term
        Σθ = σ^2 .* Matrix(transform_covariance(ch, EuclideanManifold(ch), Σ̃v))
        Σm = propagate(transform_deriv_params(HomographyMat{Float64}(Tuple(Hu)), x0), Σθ)
        Jq = transform_deriv(PerspectiveMap(), w) * Hu[:, SOneTo(2)]   # 2×2
        Σout = Matrix(Σm) + σ^2 .* Matrix(Jq * Σq * Jq')
        d = [X̂[1] - X0[1], X̂[2] - X0[2]]
        inside = _mahalanobis_inside(d, Σout, k2)
        inside === nothing && return nothing
        return (inside,)
    end
    return trial
end

"""
    epipolar_band_trial(model_class::Symbol; σ_px, f=600.0, regime=:generic,
                        aniso=false, img2_scale=1.0, level=0.95, nspan=40,
                        npts=minimal, estimate=nothing, covariance=nothing)

Criminisi-protocol output-domain trial for the epipolar models
(`model_class ∈ (:E, :F)`): per trial, perturb the minimal computation
correspondences in both images, TRACK the ground-truth-anchored solution on
the perturbed constraints, perturb a query point x in image 1, form the MC
epipolar line l̂ = θ̂·x̃_q, and test it against the analytic H–Z envelope band
at θ_gt whose Σ_l composes the model term ((x̃ᵀ⊗I₃)·Σ_θ·(x̃⊗I₃)ᵀ) with the
query term (F·σ²Σ_q̃·Fᵀ). Two statistics per trial:
`(pointwise, whole_line)` — pointwise at one random station on the nominal
line against the χ²₁ band; whole-line over the visible span against the χ²₂
band (the H–Z whole-line convention). Returns `nothing` on tracking
divergence / degenerate anchor / query line missing the view. `npts` (default
7 for F, 5 for E), `estimate`, `covariance`: the hooks (see the chart-domain
section header).

`cameras = (cam1, cam2)` (`:E` only) makes the trial camera-aware: the
COMPUTATION correspondences are projected through two real cameras, perturbed
in PIXELS with `σ_px`, and handed to the estimate and the covariance (the
hooks, or the defaults) as bearings carrying `M₁`/`M₂`. See [`essential_trial`](@ref) for why the noise model must
move with them, and use two different focal lengths.

The QUERY does not move. An essential matrix's epipolar line is a
calibrated-plane object, so the query point, the line and the band stay there,
and the query's noise is carried into that plane through view 1's own linear
part. Two σ in one trial is not frame MIXING — it is the rule applied once per
frame, which is what "σ moves with the data" requires of a trial spanning two.
The default path uses an identity carrier, so it reduces to the original
expression exactly — which is what shows the generalisation did not change the
case it generalises.

# What this trial still CANNOT validate, and why that is a choice

A query point and a band expressed in the z = 1 chart cannot represent a ray
at or past 90° from the optical axis — precisely the case the bearing work
exists for. So the ESTIMATION side of this trial is now camera-general while
its QUERY side remains pinhole-shaped BY CONSTRUCTION, and the harness
therefore **cannot validate E's output-domain covariance at a fisheye
periphery**. It is scoped that way deliberately, but it is exactly the kind of
gap someone later assumes has been closed because the rest of the trial went
camera-aware.

This is the FIFTH site of the calibrated-plane assumption in the stack — after
`_mapped_bearing`, the deleted 2-vector `_bearing` lift, `cheiral_pose_fast`
and this harness's own correspondence interface — and the first one kept on
purpose rather than removed. The generalisation (a spherical band on the
bearing's tangent plane) is a post-release item; until it lands, a fisheye
claim about this band is unsupported by anything here.
"""
function epipolar_band_trial(
        model_class::Symbol; σ_px::Float64, f::Float64 = 600.0,
        regime::Symbol = :generic, aniso::Bool = false,
        img2_scale::Float64 = 1.0, level::Float64 = 0.95,
        nspan::Int = 40, npts::Int = model_class === :F ? 7 : 5,
        estimate = nothing, covariance = nothing, cameras = nothing
    )
    cameras === nothing || model_class === :E || throw(
        ArgumentError("epipolar_band_trial: `cameras` applies to :E only (F is a pixel-plane model).")
    )
    k2_line = quantile(Chisq(2), level)
    k2_pt = quantile(Chisq(1), level)
    T = fundmat_norm_xform()
    Tit = inv(T)'
    function trial(rng)
        # `Aq` carries a data-frame displacement into the frame the QUERY and
        # the epipolar line live in. Identity everywhere except camera-aware E,
        # where the data is pixels and the line is calibrated.
        local truth, cs, σ, rect
        Aq = SMatrix{2, 2, Float64, 4}(1, 0, 0, 1)
        if model_class === :F
            _, _, Fpx, _, cs_px, _ = sample_twoview_scene(rng, npts; regime = regime, f = f)
            truth = FundMat{Float64}(Tuple(Tit * SMatrix{3, 3, Float64, 9}(Fpx) * inv(T)))
            cs = [
                Point2{Float64}(to_euclidean(T * to_affine(c.first))) =>
                    Point2{Float64}(to_euclidean(T * to_affine(c.second)))
                    for c in cs_px
            ]
            σ = σ_px * F_NORM_SCALE
            rect = Rect2(-10.0, -10.0, 20.0, 20.0)   # cal-frame view
        else
            _, _, _, E, _, cs_nm = sample_twoview_scene(rng, npts; regime = regime, f = f)
            truth = E
            rect = Rect2(-0.5, -0.5, 1.0, 1.0)       # K-normalized view
            if cameras === nothing
                cs = cs_nm
                σ = σ_px / f
            else
                # CAMERA-AWARE. The computation correspondences move to PIXELS
                # with σ_px, and the estimate and covariance get bearings below. The QUERY
                # does NOT move: an essential matrix's epipolar line is a
                # calibrated-plane object, so the query stays there and its
                # noise is carried into that plane through view 1's own linear
                # part `Aq`. Two σ in one trial is not frame MIXING — it is the
                # rule being obeyed twice, once per frame, which is exactly
                # what "σ moves with the data" demands when a trial spans two.
                cam1, _ = cameras
                cs = _pixel_pairs(cameras[1], cameras[2], cs_nm)
                σ = σ_px
                Ki = inv(SMatrix{3, 3, Float64, 9}(calibration_matrix(cam1)))
                Aq = SMatrix{2, 2, Float64, 4}(Ki[1, 1], Ki[2, 1], Ki[1, 2], Ki[2, 2])
            end
        end
        k = length(cs)
        shapes = make_point_covs(rng, k; aniso = aniso, img2_scale = img2_scale)
        # query point: uniform in the central 80% of the image-1 view
        o, wd = rect.origin, rect.widths
        x0 = Point2{Float64}(
            o[1] + wd[1] * (0.1 + 0.8 * rand(rng)),
            o[2] + wd[2] * (0.1 + 0.8 * rand(rng))
        )
        Σq = make_query_cov(rng; aniso = aniso)
        csn = perturb_pairs(rng, cs, σ, shapes)
        δq = Aq * _gaussian_offset(rng, σ, Σq)
        ch = minimal_manifold(truth)
        # The estimate and covariance get bearings when cameras are given —
        # what an E problem takes — and the untouched `cs`/`csn` otherwise.
        cs_h, csn_h = if model_class === :E && cameras !== nothing
            _bearing_csponds(cameras[1], cameras[2], cs),
                _bearing_csponds(cameras[1], cameras[2], csn)
        else
            cs, csn
        end
        Σ̃v = _trial_covariance(covariance, ch, cs_h, shapes)
        Σ̃v === nothing && return nothing
        est = _trial_estimate(estimate, ch, cs_h, csn_h)
        est === nothing && return nothing
        θ̂ = SMatrix{3, 3, Float64, 9}(Tuple(est[1]))
        Mu = SMatrix{3, 3, Float64, 9}(Tuple(model(ch)))      # SAME representative
        x̃0 = SVector{3, Float64}(x0[1], x0[2], 1.0)
        x̃q = SVector{3, Float64}(x0[1] + δq[1], x0[2] + δq[2], 1.0)
        l̂ = θ̂ * x̃q
        l0 = Mu * x̃0
        # composed line covariance: the model term is `epipolar_band`'s own (the
        # function under test), the query term folded in as its docstring says
        Σθ = σ^2 .* Matrix(transform_covariance(ch, EuclideanManifold(ch), Σ̃v))
        # The query term in the LINE's frame: the data-frame shape carried
        # through `Aq`, scaled by the same σ that perturbed it. Identity `Aq`
        # reduces this to the original expression exactly.
        Σqf = Aq * SMatrix{2, 2, Float64, 4}(Σq) * Aq'
        Σq̃ = SMatrix{3, 3, Float64, 9}(
            σ^2 * Σqf[1, 1], σ^2 * Σqf[2, 1], 0.0,
            σ^2 * Σqf[1, 2], σ^2 * Σqf[2, 2], 0.0,
            0.0, 0.0, 0.0
        )
        Σl = SMatrix{3, 3, Float64, 9}(Symmetric(epipolar_band(model(ch), Σθ, x0).Σl + Mu * Σq̃ * Mu'))
        band2 = LineConfidenceBand(SVector{3, Float64}(l0), Σl, k2_line)
        band1 = LineConfidenceBand(SVector{3, Float64}(l0), Σl, k2_pt)
        # nominal line's visible segment (station frame for both statistics)
        seg = clip_to_rect(Line2D{Float64}(SVector{3, Float64}(l0)), rect)
        seg === nothing && return nothing        # nominal line outside the view
        p1 = SVector{2, Float64}(seg.points[1])
        p2 = SVector{2, Float64}(seg.points[2])
        dseg = p2 - p1
        L = norm(dseg)
        L < eps() && return nothing
        n̂ = SVector{2, Float64}(-dseg[2], dseg[1]) / L
        ñ = SVector{3, Float64}(n̂[1], n̂[2], 0.0)
        # pointwise: MC line's crossing of ONE random station's normal section
        p = p1 + rand(rng) * dseg
        p̃ = SVector{3, Float64}(p[1], p[2], 1.0)
        den = dot(l̂, ñ)
        pointwise = if abs(den) < eps() * norm(l̂)
            false                                 # MC line parallel to the normal
        else
            s = -dot(l̂, p̃) / den
            in_band(band1, p + s * n̂)
        end
        # whole-line: the MC line inside the χ²₂ band across the visible span
        whole = true
        for t in range(0.0, 1.0; length = nspan)
            pt = p1 + t * dseg
            p̃t = SVector{3, Float64}(pt[1], pt[2], 1.0)
            dent = dot(l̂, ñ)
            if abs(dent) < eps() * norm(l̂)
                whole = false
                break
            end
            st = -dot(l̂, p̃t) / dent
            if !in_band(band2, pt + st * n̂)
                whole = false
                break
            end
        end
        return (pointwise, whole)
    end
    return trial
end

