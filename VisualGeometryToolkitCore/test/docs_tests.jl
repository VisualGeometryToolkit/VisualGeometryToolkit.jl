# docs_tests.jl — the docstring gates the Documenter build cannot run. Its
# `checkdocs = :public` only sees docstrings that exist, so a public name with
# none, a docstring detached from its definition by a blank or comment line
# (Julia 1.12 makes it a bare string: `nearest_point` and `backproject(::CameraModel, u)`
# lost theirs that way) and a signature line that drifted from the methods (a
# removed keyword) all get through it. The General registration review asks for every
# public name to be documented (#173032).
#
# Two lists, kept apart:
# - EXCEPTIONS: a name that is not documented here ON PURPOSE, with its reason.
# - BACKLOG: names still to document (the docs review of 2026-11-04 stopped at
#   these). The list only shrinks: a name documented must leave it, and a new
#   public name without a docstring fails.

@testitem "docs: every public name has a docstring, attached, and its signatures match the methods" begin
    using Test, VisualGeometryToolkitCore
    using VisualGeometryToolkitCore: test_docs

    EXCEPTIONS = Dict(
        # FlexUnits' @generate_registry_exports writes these into StackUnits; they are
        # FlexUnits' documented parsers on the stack's registry (units.md), and a
        # unit name from outside is read only by `parse_unit`.
        "StackUnits.@D_str" => "generated by FlexUnits",
        "StackUnits.@U_str" => "generated by FlexUnits",
        "StackUnits.@q_str" => "generated by FlexUnits",
        "StackUnits.@u_str" => "generated by FlexUnits",
        "StackUnits.@ud_str" => "generated by FlexUnits",
        "StackUnits.qparse" => "generated by FlexUnits",
        "StackUnits.uparse" => "generated by FlexUnits",
        "StackUnits.register_unit" => "generated by FlexUnits",
        # The mutating forms Makie's recipe macro defines; documented with the recipe.
        "cameraplot!" => "Makie recipe's mutating form",
        "frameplot!" => "Makie recipe's mutating form",
        "matches!" => "Makie recipe's mutating form",
    )
    BACKLOG = Set([
        "Cameras.AbstractIntrinsics", "Cameras.GlobalSupport", "Cameras.LocalSupport",
        "Cameras.coefficient_names", "Cameras.pixel_intrinsics", "Primitives.DEFAULT_MAX_ASPECT_RATIO",
        "Synthetic.COVERAGE_LEVELS", "Synthetic.format_result", "Synthetic.p3p_trial",
        "UnspecifiedScale", "attribute_column", "attrs_of", "block_rows", "cd_pair",
        "check_weights", "chordal_mean_stationarity", "fill_sqrt_weights!",
        "kabsch_stationarity", "lm_workspace_type", "loss_label", "manifold_parts",
        "radial_ray", "recenter_pose",
        "rescale_radial_coeff", "sigma_max", "sq_norm", "thin_ratio", "weights_column",
        "zero_sample!",
    ])
    # The signatures a docstring states for a contract's implementers, not for a
    # method of this package.
    SIGNATURE_EXCEPTIONS = Set([
        "score!: no method accepts: score!(W, scoring, scores, residuals, problem, θ::Uncertain, n; sample = nothing, bound = -Inf) -> Float64",
    ])
    test_docs(VisualGeometryToolkitCore; exceptions = EXCEPTIONS, backlog = BACKLOG, signature_exceptions = SIGNATURE_EXCEPTIONS)
end
