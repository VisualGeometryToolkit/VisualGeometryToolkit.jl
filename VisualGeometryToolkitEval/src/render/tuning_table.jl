# =============================================================================
# The tables of a coarse-fine tuning artifact: a curve (one axis) or a surface
# (two axes) through the coarse argmin
# =============================================================================

"""
    tuning_slice(path; axes, stage = :coarse) -> (; axes, xs, values, argmin)

The objective of a coarse-fine tuning artifact (`Evaluation.save_coarse_fine_artifact`)
over the `stage` (`:coarse` or `:fine`) product grid, restricted to `axes`
(one or two axis names) through that grid's argmin on every other axis:
`xs[i]` the grid of `axes[i]`, `values` the criterion's reported value (the
mAA for a `mean_average_accuracy` criterion, else the objective) over them,
`argmin` the index of the stage's argmin within the slice.
"""
function tuning_slice(path::AbstractString; axes, stage::Symbol = :coarse)
    art = load_tuning_artifact(path)
    names = collect(String, art["axes"]); want = String.(collect(axes))
    issubset(want, names) || throw(ArgumentError("tuning_slice: $path has axes $names, not $want"))
    Y = art["$(stage)_objective"]
    J = argmin(map(y -> isnan(y) ? Inf : y, Y))
    keep = [n in want for n in names]
    V = Y[[keep[i] ? Colon() : J[i] for i in eachindex(names)]...]
    crit = art.spec.scheme.criterion
    return (; axes = names[keep], xs = [collect(art.grids[Symbol(stage, "|", n)]) for n in names[keep]],
            values = crit isa MeanAverageAccuracy ? -V : V, argmin = Tuple(J)[keep])
end

"""
    emit_tuning_table(path, out; axes, labels, stage = :coarse, fmt = "%.3f") -> out

[`tuning_slice`](@ref) as a LaTeX `tabular` written to `out`: one axis, a
two-column curve (value, criterion); two axes, a surface (rows the first axis,
columns the second). `labels` names the axes in the header; `fmt` formats
the axis values. The argmin cell is starred.
"""
function emit_tuning_table(path::AbstractString, out::AbstractString; axes, labels,
                           stage::Symbol = :coarse, fmt::AbstractString = "%.3f")
    s = tuning_slice(path; axes, stage)
    art = load_tuning_artifact(path)
    fx = Printf.Format(fmt); x(v) = Printf.format(fx, v)
    cell(I) = @sprintf("%.4f", s.values[I...]) * (Tuple(I) == s.argmin ? "\$^\\star\$" : "")
    io = IOBuffer()
    println(io, "% Auto-generated by VisualGeometryToolkitEval.Render.emit_tuning_table from $(basename(path)) " *
                "(tuning $(art.spec.name), hash $(art.hash), $stage grid).")
    crit = tuning_criterion_label(art.spec.scheme.criterion)
    if length(s.axes) == 1
        println(io, "\\begin{tabular}{@{}rr@{}}\n\\toprule\n$(only(labels)) & $crit \\\\\n\\midrule")
        foreach(i -> println(io, x(s.xs[1][i]), " & ", cell((i,)), " \\\\"), eachindex(s.xs[1]))
    else
        println(io, "\\begin{tabular}{@{}r", "r"^length(s.xs[2]), "@{}}\n\\toprule")
        println(io, "$crit: $(labels[1]) \\textbackslash{} $(labels[2]) & ", join(x.(s.xs[2]), " & "), " \\\\\n\\midrule")
        foreach(i -> println(io, x(s.xs[1][i]), " & ", join([cell((i, j)) for j in eachindex(s.xs[2])], " & "), " \\\\"),
                eachindex(s.xs[1]))
    end
    println(io, "\\bottomrule\n\\end{tabular}")
    mkpath(dirname(abspath(out)))
    write(out, take!(io))
    return out
end
